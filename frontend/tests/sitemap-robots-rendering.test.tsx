// @vitest-environment node
/**
 * The sitemap's *rendered documents* — the routes called, the XML parsed, the URLs
 * checked.
 *
 * **The unit tests above check the documents the builders compose. This file checks the
 * documents the server actually serves** — the route handlers run, their output is
 * parsed as XML, and every URL inside is examined. A builder that composes a correct
 * `<urlset>` is worth nothing if the route never calls it, and a route that serves a
 * malformed document is worth nothing to a crawler.
 *
 * **The feed is mocked, and the mock is the whole point.** The sitemap's *membership* is
 * the backend's business — it is the public surface, and the backend's own tests assert
 * that no `in_review` event, no superseded event and no below-threshold city appears in
 * it. What this file checks is the sitemap's own claim: **it renders the feed, and
 * nothing else.** A URL in a sitemap that the feed did not name is a sitemap that has
 * drifted from the public surface, which is the failure the whole item is about.
 */
import { describe, expect, it, vi } from "vitest";

const GET = vi.fn();

vi.mock("@/lib/backend-client", () => ({
  api: { GET: (...args: unknown[]) => GET(...args) },
}));

vi.mock("next/cache", () => ({
  unstable_cache: (fn: (...args: unknown[]) => unknown) => fn,
}));

/**
 * **The origin is stubbed, so the documents are deterministic.**
 *
 * `siteUrl()` falls back to the local address in a test run, and a document whose
 * `<loc>` values depend on the environment is a document the tests cannot compare.
 * The stub is the site's public origin — the same one a deployment would set.
 */
vi.stubEnv("PUBLIC_SITE_URL", "https://eventpulse24.test");

/** The sitemap's own route handlers, imported after the mocks are in place. */
const { GET: indexRoute } = await import("@/app/sitemap.xml/route");
const { GET: childRoute } = await import("@/app/sitemap/[id]/route");

/** The origin the documents resolve against. */
const ORIGIN = "https://eventpulse24.test";

/** One feed entry, in the shape the backend sends it. */
function entry(path: string, kind: "event" | "city" = "event") {
  return { kind, last_modified: "2026-08-20T09:14:00Z", path };
}

/** A feed page, in the shape the backend sends it. */
function feed(items: { path: string; kind: "event" | "city" }[], total = items.length) {
  return {
    has_next: false,
    items: items.map((item) => ({ ...item, last_modified: "2026-08-20T09:14:00Z" })),
    page: 1,
    page_size: 1000,
    total,
  };
}

/**
 * The `<loc>` values in a document.
 *
 * **A regex, not an XML parser.** The documents are generated by this codebase and
 * their shape is known — one `<loc>` per line, one `<url>` per entry — and the parser
 * would be a dependency for a job the regex does. The regex is anchored on the line, so
 * it cannot match a `<loc>` that appeared inside another element's text.
 */
function locations(document: string): string[] {
  return [...document.matchAll(/<loc>([^<]*)<\/loc>/g)].map((match) => match[1] ?? "");
}

/**
 * The `<loc>` values in a document, as **paths**.
 *
 * **The path is the claim; the origin is the deployment's business.** The absolute URL
 * is the path resolved against `PUBLIC_SITE_URL`, so comparing the paths is comparing
 * the thing the sitemap actually asserts.
 */
function paths(document: string): string[] {
  return locations(document).map((location) => new URL(location).pathname);
}

/** The `<lastmod>` values in a document. */
function lastmods(document: string): string[] {
  return [...document.matchAll(/<lastmod>([^<]*)<\/lastmod>/g)].map((match) => match[1] ?? "");
}

/** The child route's context, in the shape Next hands it. */
function childContext(id: string) {
  return { params: Promise.resolve({ id }) };
}

describe("the sitemap index route", () => {
  it("serves a sitemapindex naming one child", async () => {
    GET.mockResolvedValue({ data: feed([entry("/events/slug-1")]), response: { status: 200 } });

    const response = await indexRoute();

    expect(response.status).toBe(200);
    expect(response.headers.get("Content-Type")).toContain("application/xml");

    const document = await response.text();
    expect(document).toContain("<sitemapindex");
    expect(document).toContain(`<loc>${ORIGIN}/sitemap/0.xml</loc>`);
  });

  it("serves a 503 when the feed cannot be read", async () => {
    // **A sitemap that lists nothing says "this site has no pages"**, and a sitemap that
    // lists half the pages says something just as false. A crawler takes the document
    // as the truth.
    GET.mockResolvedValue({ data: undefined, response: { status: 500 } });

    const response = await indexRoute();

    expect(response.status).toBe(503);
  });

  it("serves a 503 when the feed cannot be read at all", async () => {
    GET.mockRejectedValue(new Error("the network is down"));

    const response = await indexRoute();

    expect(response.status).toBe(503);
  });
});

describe("the child sitemap route", () => {
  it("serves a urlset holding the feed's URLs", async () => {
    GET.mockResolvedValue({
      data: feed([entry("/events/slug-1"), entry("/events-in-brooklyn", "city")]),
      response: { status: 200 },
    });

    const response = await childRoute(
      new Request("http://localhost/sitemap/0.xml"),
      childContext("0.xml"),
    );

    expect(response.status).toBe(200);

    const document = await response.text();
    expect(document).toContain("<urlset");
    expect(paths(document)).toEqual(["/events/slug-1", "/events-in-brooklyn"]);
  });

  it("gives every URL a lastmod", async () => {
    // **The feed knows it, so the sitemap says it.** A crawler is told the truth about
    // what moved, and can skip what has not.
    GET.mockResolvedValue({
      data: feed([entry("/events/slug-1"), entry("/events-in-brooklyn", "city")]),
      response: { status: 200 },
    });

    const response = await childRoute(
      new Request("http://localhost/sitemap/0.xml"),
      childContext("0.xml"),
    );

    const document = await response.text();
    expect(lastmods(document)).toHaveLength(2);
    expect(lastmods(document)[0]).toBe("2026-08-20T09:14:00Z");
  });

  it("serves a 404 for a child that does not exist", async () => {
    const response = await childRoute(
      new Request("http://localhost/sitemap/abc.xml"),
      childContext("abc.xml"),
    );

    expect(response.status).toBe(404);
    expect(GET).not.toHaveBeenCalled();
  });

  it("serves a 404 for a child beyond the end of the feed", async () => {
    // **A child the index does not name does not exist.** The feed holds one URL, so
    // the index names one child; a request for child 9 is a request for a sitemap that
    // is not there. An empty `<urlset>` would say "this site has no pages", which is
    // false, and false in the way that erodes a crawler's trust in the document.
    GET.mockResolvedValue({
      data: feed([entry("/events/slug-1")]),
      response: { status: 200 },
    });

    const response = await childRoute(
      new Request("http://localhost/sitemap/9.xml"),
      childContext("9.xml"),
    );

    expect(response.status).toBe(404);
    expect(await response.text()).not.toContain("<urlset");
  });

  it("serves a 503 when the feed cannot be read", async () => {
    GET.mockResolvedValue({ data: undefined, response: { status: 500 } });

    const response = await childRoute(
      new Request("http://localhost/sitemap/0.xml"),
      childContext("0.xml"),
    );

    expect(response.status).toBe(503);
  });
});

describe("the sitemap's membership", () => {
  it("lists exactly the URLs the feed named — and no others", async () => {
    // **The whole point of the item.** A sitemap that lists a URL the public surface
    // does not serve is a crawl-budget leak: the crawler spends a fetch to learn the URL
    // does not exist.
    const named = [
      entry("/events/slug-1"),
      entry("/events/slug-2"),
      entry("/events-in-brooklyn", "city"),
    ];
    GET.mockResolvedValue({ data: feed(named), response: { status: 200 } });

    const response = await childRoute(
      new Request("http://localhost/sitemap/0.xml"),
      childContext("0.xml"),
    );
    const document = await response.text();

    expect(paths(document)).toEqual(named.map((item) => item.path));
  });

  it("never lists an authed or dev path", async () => {
    // **The sitemap is the public surface.** An authed route in it would send a crawler
    // to a sign-in, and the crawler would record the sign-in as the page's content.
    const named = [entry("/events/slug-1")];
    GET.mockResolvedValue({ data: feed(named), response: { status: 200 } });

    const response = await childRoute(
      new Request("http://localhost/sitemap/0.xml"),
      childContext("0.xml"),
    );
    const document = await response.text();

    for (const prefix of [
      "/settings",
      "/timeline",
      "/conflicts",
      "/onboarding",
      "/dev",
      "/signin",
    ]) {
      expect(paths(document), `${prefix} is in the sitemap`).not.toContain(prefix);
    }
  });

  it("never lists an event's UUID — the Detail Screen is not a public URL", async () => {
    const named = [entry("/events/slug-1")];
    GET.mockResolvedValue({ data: feed(named), response: { status: 200 } });

    const response = await childRoute(
      new Request("http://localhost/sitemap/0.xml"),
      childContext("0.xml"),
    );
    const document = await response.text();

    // **The UUID shape is a UUIDv7.** The feed never carries one — the backend's
    // membership rule is "a published, non-superseded event", keyed on its slug — so
    // this is a backstop against a future change that listed ids.
    expect(document).not.toMatch(/\/events\/[0-9a-f]{8}-[0-9a-f]{4}-/i);
  });
});
